--    nombre, categoria, precio, descripcion, stock y activo. Ninguna parte del
--    codigo la usaba. Por eso esta seccion no asume nada:
--
--      1. Si la tabla no existe, la crea completa.
--      2. Si existe, le AGREGA las columnas que faltan. No borra ni cambia el
