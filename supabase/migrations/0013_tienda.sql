-- ----------------------------------------------------------------------------
-- suscribir_newsletter
-- ----------------------------------------------------------------------------
-- Idempotente y muda: suscribir un correo ya registrado responde igual que uno
-- nuevo, para no revelar quien esta suscrito.
create or replace function public.suscribir_newsletter(p_email text)
  returns void
  language plpgsql
  security definer
  set search_path = public, pg_temp
as $$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
begin
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(v_email) > 254 then
    raise exception 'Revisa tu correo.' using errcode = 'P0001';
  end if;

  insert into public.suscripciones_newsletter (email)
  values (v_email)
  on conflict (email) do nothing;
end;
$$;

revoke all on function public.suscribir_newsletter(text) from public;
grant execute on function public.suscribir_newsletter(text) to anon, authenticated;

-- ----------------------------------------------------------------------------
-- Catalogo inicial
-- ----------------------------------------------------------------------------
-- Los 10 productos de la especificacion.
--
-- El servicio vinculado se busca por patrones en orden de prioridad, no por un
-- nombre fijo: el catalogo real ya no coincide con seed.sql («Esculpido de
-- Uñas» paso a ser «Extenciones en poligel», y no hay servicio facial). Gana el
-- primer patron que encuentre un servicio activo; si ninguno encuentra, el
-- producto queda sin vinculo en vez de fallar. Se puede corregir despues desde
-- el dashboard con un UPDATE de servicio_id.
insert into public.productos
  (slug, nombre, categoria, tamano, precio, precio_anterior, insignia, servicio_id,
   descripcion, modo_uso, ingredientes, orden)
select
