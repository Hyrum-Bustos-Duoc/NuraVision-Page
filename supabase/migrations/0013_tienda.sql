do $$
begin
  if not exists (select 1 from pg_type where typname = 'entrega_pedido') then
    create type public.entrega_pedido as enum ('despacho', 'retiro', 'cita');
  end if;
  if not exists (select 1 from pg_type where typname = 'metodo_pago_pedido') then
    create type public.metodo_pago_pedido as enum ('webpay', 'transferencia', 'estudio');
  end if;
  if not exists (select 1 from pg_type where typname = 'estado_pedido') then
    create type public.estado_pedido as enum (
      'pendiente_pago',
      'pagado',
      'preparando',
      'listo',
      'despachado',
      'entregado',
      'cancelado'
    );
  end if;
end
$$;

