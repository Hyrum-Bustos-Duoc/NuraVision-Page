-- ============================================================================
-- NuraVision · 0013 · Tienda, pedidos y newsletter
-- ============================================================================
-- Agrega la venta de productos del Diseño 1 «Tienda»:
--
--   · productos                  catalogo publico, gestionado por el personal.
--   · pedidos / pedido_items     compras, con o sin cuenta (igual que reservas).
--   · suscripciones_newsletter   correos del footer.
--   · crear_pedido()             UNICA via para crear un pedido.
--   · suscribir_newsletter()     UNICA via para suscribirse.
--
-- Es aditiva: no modifica ninguna tabla anterior y se puede reaplicar (usa
-- "if not exists" y "on conflict do nothing").
--
-- POR QUE LOS PEDIDOS SE CREAN CON UNA FUNCION Y NO CON INSERT:
-- Con un INSERT abierto, el total lo fijaria el navegador, y cualquiera con la
-- anon key podria comprar el kit a $1. La funcion recibe solo productos y
-- cantidades, y calcula precios, despacho y descuentos leyendo la base. Por eso
-- `pedidos` y `pedido_items` no conceden INSERT a nadie.
--
-- Las reglas de dinero viven aqui y tienen un espejo en
-- frontend/src/modules/pedidos/domain/pedido.reglas.ts, que solo sirve para
-- mostrar el resumen antes de pagar. Si cambias una, cambia la otra: si no, el
-- resumen y lo cobrado no coincidirian.
-- ============================================================================

