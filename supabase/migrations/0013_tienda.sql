-- ----------------------------------------------------------------------------
-- crear_pedido
-- ----------------------------------------------------------------------------
-- security definer: corre con los permisos del dueño para poder insertar en
-- tablas que el navegador no puede escribir. Todo lo que entra se valida aqui,
-- porque esta funcion es la unica puerta.
--
-- p_items: [{"slug": "aceite-de-cuticula-nura", "cantidad": 2}, ...]
--
-- Los errores pensados para la clienta usan errcode P0001 y un mensaje en
-- español listo para mostrar.
create or replace function public.crear_pedido(
  p_items        jsonb,
  p_nombre       text,
  p_email        text,
  p_entrega      public.entrega_pedido,
  p_metodo_pago  public.metodo_pago_pedido,
  p_direccion    text   default null,
  p_comuna       text   default null,
  p_reserva_id   bigint default null,
  p_telefono     text   default null
)
  returns table (
    pedido_id    bigint,
    codigo       text,
    subtotal     integer,
    costo_envio  integer,
    descuento    integer,
    total        integer
  )
  language plpgsql
  security definer
  set search_path = public, pg_temp
as $$
#variable_conflict use_column
declare
  -- Reglas de dinero. Espejo en pedido.reglas.ts.
  c_costo_despacho    constant integer := 3990;
  c_umbral_gratis     constant integer := 40000;
  c_descuento_combo   constant numeric := 0.15;
  c_max_lineas        constant integer := 30;

  v_uid               uuid := auth.uid();
  v_servicio_cita     bigint;
  v_comuna_norm       text;
  v_codigo            text;
  v_pedido_id         bigint;
  v_subtotal          integer := 0;
  v_descuento         integer := 0;
  v_envio             integer := 0;
  v_linea             record;
begin
  -- --- Contacto -------------------------------------------------------------
  if nullif(btrim(coalesce(p_nombre, '')), '') is null then
    raise exception 'Necesitamos tu nombre para el pedido.' using errcode = 'P0001';
  end if;
  if coalesce(btrim(p_email), '') !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'Revisa tu correo: lo necesitamos para avisarte del pedido.'
      using errcode = 'P0001';
  end if;

  -- --- Productos ------------------------------------------------------------
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Tu carrito está vacío.' using errcode = 'P0001';
  end if;
  if jsonb_array_length(p_items) > c_max_lineas then
    raise exception 'El pedido tiene demasiadas líneas.' using errcode = 'P0001';
  end if;

  -- Se agrupa por slug: dos lineas del mismo producto suman cantidad en vez de
  -- saltarse el tope por linea.
  drop table if exists pg_temp._lineas;
  create temporary table _lineas on commit drop as
  select
    e ->> 'slug'                          as slug,
    sum((e ->> 'cantidad')::integer)      as cantidad
  from jsonb_array_elements(p_items) as e
  where coalesce(e ->> 'cantidad', '') ~ '^[0-9]{1,3}$'
  group by e ->> 'slug';

  if (select count(*) from _lineas) <> (
       select count(distinct e ->> 'slug') from jsonb_array_elements(p_items) e
     ) then
    raise exception 'Hay una cantidad no válida en el carrito.' using errcode = 'P0001';
  end if;
  if exists (select 1 from _lineas where cantidad < 1 or cantidad > 20) then
    raise exception 'Cada producto admite entre 1 y 20 unidades.' using errcode = 'P0001';
  end if;

  -- --- Entrega --------------------------------------------------------------
  if p_entrega = 'despacho' then
    if nullif(btrim(coalesce(p_direccion, '')), '') is null then
      raise exception 'Falta la dirección de despacho.' using errcode = 'P0001';
    end if;
    -- Cobertura: Viña del Mar y Valparaíso. Se compara sin tildes ni
    -- mayusculas, que es como la escribe la gente.
    v_comuna_norm := translate(lower(btrim(coalesce(p_comuna, ''))), 'áéíóúñ', 'aeioun');
    if v_comuna_norm not in ('vina del mar', 'valparaiso') then
      raise exception 'Por ahora despachamos solo en Viña del Mar y Valparaíso.'
        using errcode = 'P0001';
    end if;
    if p_metodo_pago = 'estudio' then
      raise exception 'Pagar en el estudio solo está disponible con retiro o entrega en tu cita.'
        using errcode = 'P0001';
    end if;
  elsif p_entrega = 'cita' then
    if v_uid is null then
      raise exception 'Inicia sesión para recibir el pedido en tu cita.' using errcode = 'P0001';
    end if;
    -- La reserva tiene que ser propia, futura y seguir viva.
    select r.servicio_id
      into v_servicio_cita
      from public.reservas r
     where r.id = p_reserva_id
       and r.cliente_id = v_uid
       and r.estado in ('pendiente', 'confirmada')
       and r.fecha >= (now() at time zone 'America/Santiago')::date;
    if not found then
      raise exception 'No encontramos una reserva vigente a tu nombre para entregar el pedido.'
        using errcode = 'P0001';
    end if;
  end if;

  -- --- Precios y stock ------------------------------------------------------
  if exists (
    select 1
      from _lineas l
      left join public.productos p on p.slug = l.slug and p.activo
     where p.id is null
  ) then
    raise exception 'Un producto de tu carrito ya no está disponible. Revisa el carrito.'
      using errcode = 'P0001';
  end if;

  -- FOR UPDATE bloquea las filas hasta el fin de la transaccion: dos compras
  -- simultaneas del ultimo kit no pueden pasar las dos.
  for v_linea in
    select l.slug, l.cantidad, p.id, p.nombre, p.precio, p.stock,
           p.categoria, p.servicio_id
      from _lineas l
      join public.productos p on p.slug = l.slug
     order by p.id
       for update of p
  loop
    if v_linea.stock is not null and v_linea.stock < v_linea.cantidad then
      raise exception 'No nos queda stock suficiente de %.', v_linea.nombre
        using errcode = 'P0001';
    end if;
    v_subtotal := v_subtotal + v_linea.precio * v_linea.cantidad;
    -- Combo: 15 % en los kits vinculados al servicio de la cita.
    if p_entrega = 'cita' and v_linea.categoria = 'kits'
       and v_linea.servicio_id is not null and v_linea.servicio_id = v_servicio_cita then
      v_descuento := v_descuento + round(v_linea.precio * v_linea.cantidad * c_descuento_combo)::integer;
    end if;
  end loop;

  if p_entrega = 'despacho' and v_subtotal < c_umbral_gratis then
    v_envio := c_costo_despacho;
  end if;

  -- --- Codigo ---------------------------------------------------------------
  loop
    v_codigo := 'NV-P-' || lpad((floor(random() * 1000000))::integer::text, 6, '0');
    exit when not exists (select 1 from public.pedidos x where x.codigo = v_codigo);
  end loop;

  -- --- Escritura ------------------------------------------------------------
  insert into public.pedidos as p (
    codigo, cliente_id, cliente_nombre, cliente_email, cliente_telefono,
    entrega, direccion, comuna, reserva_id, metodo_pago,
    subtotal, costo_envio, descuento, total
  )
  values (
    v_codigo, v_uid, btrim(p_nombre), lower(btrim(p_email)), nullif(btrim(coalesce(p_telefono, '')), ''),
    p_entrega,
    case when p_entrega = 'despacho' then btrim(p_direccion) end,
    case when p_entrega = 'despacho' then btrim(p_comuna) end,
    case when p_entrega = 'cita' then p_reserva_id end,
    p_metodo_pago,
    v_subtotal, v_envio, v_descuento, v_subtotal + v_envio - v_descuento
  )
  returning p.id into v_pedido_id;

  insert into public.pedido_items (pedido_id, producto_id, nombre, precio_unitario, cantidad, descuento)
  select
    v_pedido_id, p.id, p.nombre, p.precio, l.cantidad,
    case
      when p_entrega = 'cita' and p.categoria = 'kits'
           and p.servicio_id is not null and p.servicio_id = v_servicio_cita
        then round(p.precio * l.cantidad * c_descuento_combo)::integer
      else 0
    end
  from _lineas l
  join public.productos p on p.slug = l.slug;

  update public.productos p
     set stock = p.stock - l.cantidad
    from _lineas l
   where p.slug = l.slug
     and p.stock is not null;

  return query
  select v_pedido_id, v_codigo, v_subtotal, v_envio, v_descuento,
         v_subtotal + v_envio - v_descuento;
end;
$$;

